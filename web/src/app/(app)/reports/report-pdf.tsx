import "server-only";

import { Document, Line, Page, Rect, StyleSheet, Svg, Text, View, renderToBuffer } from "@react-pdf/renderer";
import type { Report, ReportFilters } from "@/lib/incident-stats";
import { chartScale, monthTotal, type MonthlyCount, type ReportSeries } from "@/lib/report-series";
import { REPORT_SOURCE_NOTE, filterLabels } from "@/lib/report-view";
import { PLANTATION_LOCATION } from "@/lib/weather";

// The Reports PDF (A4, built-in Helvetica). Same filters, series and counts as
// the Reports page; only the layout differs.

const INK = "#16241b";
const MUTED = "#5d6b62";
const LINE = "#e2e6dc";
const LEAF = "#255939";

const styles = StyleSheet.create({
  page: { paddingTop: 40, paddingBottom: 56, paddingHorizontal: 40, fontFamily: "Helvetica", fontSize: 10, color: INK },
  brand: { fontSize: 9, fontFamily: "Helvetica-Bold", color: LEAF, letterSpacing: 1 },
  title: { marginTop: 4, fontSize: 18, fontFamily: "Helvetica-Bold" },
  meta: { marginTop: 6, gap: 2, color: MUTED },
  section: { marginTop: 18 },
  heading: { fontSize: 12, fontFamily: "Helvetica-Bold", marginBottom: 8 },
  subheading: { fontSize: 9, color: MUTED, marginTop: -5, marginBottom: 8 },
  filterRow: { flexDirection: "row", paddingVertical: 3, borderBottomWidth: 1, borderBottomColor: LINE },
  filterLabel: { width: 130, color: MUTED },
  tiles: { flexDirection: "row", flexWrap: "wrap", gap: 8 },
  tile: { width: 120, borderWidth: 1, borderColor: LINE, borderRadius: 6, padding: 8 },
  tileLabel: { flexDirection: "row", alignItems: "center", gap: 4, fontSize: 8, color: MUTED },
  tileValue: { marginTop: 4, fontSize: 18, fontFamily: "Helvetica-Bold" },
  swatch: { width: 7, height: 7, borderRadius: 1 },
  legend: { flexDirection: "row", flexWrap: "wrap", gap: 12, marginBottom: 8 },
  legendItem: { flexDirection: "row", alignItems: "center", gap: 4, fontSize: 8, color: MUTED },
  tr: { flexDirection: "row", borderBottomWidth: 1, borderBottomColor: LINE, paddingVertical: 4 },
  th: { fontSize: 8, color: MUTED, fontFamily: "Helvetica-Bold" },
  monthCell: { width: 80 },
  numCell: { flex: 1, paddingLeft: 8, textAlign: "right" },
  empty: { marginTop: 18, padding: 16, borderWidth: 1, borderColor: LINE, borderStyle: "dashed", borderRadius: 6, color: MUTED, textAlign: "center" },
  note: { marginTop: 20, fontSize: 8, color: MUTED, lineHeight: 1.4 },
  footer: { position: "absolute", bottom: 24, left: 40, right: 40, flexDirection: "row", justifyContent: "space-between", fontSize: 8, color: MUTED },
});

const generatedFmt = new Intl.DateTimeFormat("en-US", {
  timeZone: PLANTATION_LOCATION.timezone,
  year: "numeric",
  month: "long",
  day: "numeric",
  hour: "numeric",
  minute: "2-digit",
});

export interface ReportPdfProps {
  filters: ReportFilters;
  report: Report;
  series: ReportSeries[];
  generatedAt: Date;
  generatedBy: { name: string; role: string };
}

/** The report as PDF bytes. */
export function renderReportPdf(props: ReportPdfProps): Promise<Buffer> {
  return renderToBuffer(<ReportPdf {...props} />);
}

function ReportPdf({ filters, report, series, generatedAt, generatedBy }: ReportPdfProps) {
  const labels = filterLabels(filters);
  const totals = report.months.map((m) => monthTotal(m, series));

  return (
    <Document title={`BanaTrack incident report ${labels.range}`} author="BanaTrack" creator="BanaTrack">
      <Page size="A4" style={styles.page}>
        <Text style={styles.brand}>BANATRACK</Text>
        <Text style={styles.title}>Incident Report</Text>
        <View style={styles.meta}>
          <Text>{PLANTATION_LOCATION.name}</Text>
          <Text>Generated {generatedFmt.format(generatedAt)} (Philippine time)</Text>
          <Text>
            Generated by {generatedBy.name} ({generatedBy.role})
          </Text>
        </View>

        <View style={styles.section}>
          <Text style={styles.heading}>Filters used</Text>
          <FilterRow label="Date range" value={labels.range} />
          <FilterRow label="Area" value={labels.area} />
          <FilterRow label="Suspected disease" value={labels.disease} />
          <FilterRow label="Current status" value={labels.status} />
        </View>

        {report.total === 0 ? (
          <Text style={styles.empty}>No incidents match these filters.</Text>
        ) : (
          <>
            <View style={styles.section}>
              <Text style={styles.heading}>Summary</Text>
              <View style={styles.tiles}>
                <Tile label="Total incidents" value={report.total} />
                {series.map((s) => (
                  <Tile key={s.key} label={s.label} value={report.totals[s.key]} color={s.color} />
                ))}
              </View>
            </View>

            <View style={styles.section} wrap={false}>
              <Text style={styles.heading}>Incidents per month</Text>
              <Text style={styles.subheading}>Stacked by suspected disease, as recorded in the field</Text>
              <View style={styles.legend}>
                {series.map((s) => (
                  <View key={s.key} style={styles.legendItem}>
                    <View style={[styles.swatch, { backgroundColor: s.color }]} />
                    <Text>{s.label}</Text>
                  </View>
                ))}
              </View>
              <Chart months={report.months} series={series} totals={totals} />
            </View>

            {/* A table of up to a year moves to the next page whole instead of splitting off a row or two;
                longer ones flow across pages with the header repeated. */}
            <View style={styles.section} wrap={report.months.length > 12}>
              <Text style={styles.heading}>Data table</Text>
              <View style={styles.tr} fixed>
                <Text style={[styles.th, styles.monthCell]}>Month</Text>
                {series.map((s) => (
                  <Text key={s.key} style={[styles.th, styles.numCell]}>{s.label}</Text>
                ))}
                <Text style={[styles.th, styles.numCell]}>Total</Text>
              </View>
              {report.months.map((m, i) => (
                <View key={m.month} style={styles.tr} wrap={false}>
                  <Text style={styles.monthCell}>{m.label}</Text>
                  {series.map((s) => (
                    <Text key={s.key} style={styles.numCell}>{m.counts[s.key]}</Text>
                  ))}
                  <Text style={[styles.numCell, { fontFamily: "Helvetica-Bold" }]}>{totals[i]}</Text>
                </View>
              ))}
            </View>
          </>
        )}

        <Text style={styles.note} wrap={false}>{REPORT_SOURCE_NOTE}</Text>

        <View style={styles.footer} fixed>
          <Text>BanaTrack · {labels.range}</Text>
          <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
        </View>
      </Page>
    </Document>
  );
}

function FilterRow({ label, value }: { label: string; value: string }) {
  return (
    <View style={styles.filterRow}>
      <Text style={styles.filterLabel}>{label}</Text>
      <Text>{value}</Text>
    </View>
  );
}

function Tile({ label, value, color }: { label: string; value: number; color?: string }) {
  return (
    <View style={styles.tile}>
      <View style={styles.tileLabel}>
        {color && <View style={[styles.swatch, { backgroundColor: color }]} />}
        <Text>{label}</Text>
      </View>
      <Text style={styles.tileValue}>{value}</Text>
    </View>
  );
}

const CHART_WIDTH = 515;
const PLOT_HEIGHT = 180;
const AXIS_WIDTH = 24;
const LABEL_HEIGHT = 16;

/** The stacked monthly columns, drawn with the same scale and colors as the page chart. */
function Chart({ months, series, totals }: { months: MonthlyCount[]; series: ReportSeries[]; totals: number[] }) {
  const { max, ticks } = chartScale(totals);
  const plotWidth = CHART_WIDTH - AXIS_WIDTH;
  const colWidth = plotWidth / months.length;
  const barWidth = Math.min(20, colWidth * 0.6);
  const y = (v: number) => PLOT_HEIGHT - (v / max) * PLOT_HEIGHT;
  // Fewer month labels when they would overlap.
  const labelEvery = colWidth < 22 ? 2 : 1;

  return (
    <Svg width={CHART_WIDTH} height={PLOT_HEIGHT + LABEL_HEIGHT + 6} viewBox={`0 -6 ${CHART_WIDTH} ${PLOT_HEIGHT + LABEL_HEIGHT + 6}`}>
      {ticks.map((t) => (
        <Line key={`g${t}`} x1={AXIS_WIDTH} x2={CHART_WIDTH} y1={y(t)} y2={y(t)} stroke={LINE} strokeWidth={0.75} />
      ))}
      {ticks.map((t) => (
        <Text key={`t${t}`} x={AXIS_WIDTH - 6} y={y(t) + 3} textAnchor="end" style={{ fontSize: 7, fill: MUTED }}>
          {String(t)}
        </Text>
      ))}
      {months.map((m, i) => {
        const x = AXIS_WIDTH + colWidth * i + (colWidth - barWidth) / 2;
        let base = 0;
        return series
          .filter((s) => m.counts[s.key] > 0)
          .map((s) => {
            const top = base + m.counts[s.key];
            const rect = (
              <Rect
                key={`${m.month}-${s.key}`}
                x={x}
                y={y(top)}
                width={barWidth}
                // A 1pt gap between segments, like the page chart.
                height={Math.max(y(base) - y(top) - (base > 0 ? 1 : 0), 0.5)}
                fill={s.color}
              />
            );
            base = top;
            return rect;
          });
      })}
      {months.map((m, i) =>
        i % labelEvery === 0 ? (
          <Text
            key={`l${m.month}`}
            x={AXIS_WIDTH + colWidth * (i + 0.5)}
            y={PLOT_HEIGHT + 12}
            textAnchor="middle"
            style={{ fontSize: 7, fill: MUTED }}
          >
            {m.label}
          </Text>
        ) : null,
      )}
    </Svg>
  );
}
